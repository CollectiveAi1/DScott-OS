import "server-only";
import { and, asc, count, eq, gte, inArray, isNotNull, lt, lte } from "drizzle-orm";
import { getDb } from "@/db/client";
import { approvals, calendarEvents, tasks, timeline } from "@/db/schema";
import { staleCaptures } from "@/modules/work/queries";
import { conflictsInRange, type Conflict } from "@/modules/schedule/queries";
import { readConnection } from "@/modules/google/tokens";
import { latestDigest } from "@/modules/learning/queries";
import { startOfDayInstant } from "./zoned";
import { addDays, dateInZone } from "./dates";
import { getSettings } from "./settings";

export type CommandSnapshot = {
  today: string;
  waitingApprovals: number;
  dueThisWeek: number;
  overdue: number;
  dealsMoved7d: number;
  nextGameOrTravel: { title: string; kind: string; startsAt: Date } | null;
  dueList: { id: string; title: string; due: string | null; arena: string; priority: string }[];
  /** Things that have gone stale and need Devon, not the Operator. More kinds arrive with M4 and M6. */
  needsAttention: { id: string; kind: string; title: string; detail: string; href: string }[];
  /** Unacknowledged clashes in the next 14 days, plus anything running into protected time. */
  conflicts: Conflict[];
  /** The most recent weekly learning review, if one has been written. */
  learningReview: { day: string; body: string } | null;
  /** Today's brief, if the 06:30 job has run or it has been regenerated by hand. */
  dailyBrief: { day: string; body: string; source: string } | null;
};

const CONFLICT_DAYS = 14;

export async function loadCommand(timeZone: string, now = new Date()): Promise<CommandSnapshot> {
  const db = getDb();
  const today = dateInZone(now, timeZone);
  const weekEnd = addDays(today, 7);
  const sevenDaysAgo = new Date(now.getTime() - 7 * 24 * 60 * 60 * 1000);
  const openWithDue = and(eq(tasks.status, "open"), isNotNull(tasks.due));

  const [waiting, dueWeek, overdueRows, moved, nextEvent, dueList, stale, conflicts, googleConnection, review, brief] =
    await Promise.all([
    db.select({ n: count() }).from(approvals).where(eq(approvals.status, "waiting")),
    db.select({ n: count() }).from(tasks).where(and(openWithDue, gte(tasks.due, today), lte(tasks.due, weekEnd))),
    db.select({ n: count() }).from(tasks).where(and(openWithDue, lt(tasks.due, today))),
    db
      .select({ n: count() })
      .from(timeline)
      .where(and(eq(timeline.kind, "stage_move"), gte(timeline.createdAt, sevenDaysAgo))),
    db
      .select({ title: calendarEvents.title, kind: calendarEvents.kind, startsAt: calendarEvents.startsAt })
      .from(calendarEvents)
      .where(and(inArray(calendarEvents.kind, ["game", "travel"]), gte(calendarEvents.endsAt, now)))
      .orderBy(asc(calendarEvents.startsAt))
      .limit(1),
    db
      .select({ id: tasks.id, title: tasks.title, due: tasks.due, arena: tasks.arena, priority: tasks.priority })
      .from(tasks)
      // Untriaged captures count too: a capture with a date is due whether or not it has been
      // filed onto a board, and the tile above this list counts it the same way.
      .where(and(openWithDue, lte(tasks.due, weekEnd)))
      .orderBy(asc(tasks.due))
      .limit(12),
    staleCaptures(db, now),
    conflictsForCommand(timeZone, today, now),
    readConnection(),
    latestDigest(db, "learning_review"),
    latestDigest(db, "daily_brief"),
  ]);

  return {
    today,
    waitingApprovals: waiting[0]?.n ?? 0,
    dueThisWeek: dueWeek[0]?.n ?? 0,
    overdue: overdueRows[0]?.n ?? 0,
    dealsMoved7d: moved[0]?.n ?? 0,
    nextGameOrTravel: nextEvent[0] ?? null,
    dueList,
    needsAttention: [
      // A revoked Google grant stops the sync silently otherwise: the Family calendar just
      // quietly stops updating, which is worse than an error.
      ...(googleConnection.status === "broken"
        ? [
            {
              id: "google-connection",
              kind: "Google Calendar",
              title: "Reconnect Google Calendar",
              detail: googleConnection.reason,
              href: "/settings",
            },
          ]
        : []),
      ...stale.map((task) => ({
        id: task.id,
        kind: "Untriaged capture",
        title: task.title,
        detail: `Captured ${dateInZone(task.createdAt, timeZone)} and still in the Misc inbox.`,
        href: "/work",
      })),
    ],
    // Acknowledged pairs are hidden: Devon has already decided that one is fine.
    conflicts: conflicts.filter((conflict) => conflict.kind === "protected" || !conflict.acknowledged),
    learningReview: review ? { day: review.day, body: review.body } : null,
    // Only today's. Yesterday's brief on this morning's screen would be worse than none.
    dailyBrief: brief && brief.day === today ? { day: brief.day, body: brief.body, source: brief.source } : null,
  };
}

async function conflictsForCommand(timeZone: string, today: string, now: Date): Promise<Conflict[]> {
  const { protectedTime } = await getSettings();
  const days = Array.from({ length: CONFLICT_DAYS }, (_, index) => addDays(today, index));
  const from = startOfDayInstant(today, timeZone);
  const to = startOfDayInstant(addDays(today, CONFLICT_DAYS), timeZone);
  // A conflict earlier today is history; the panel is about what is still ahead.
  return conflictsInRange(getDb(), new Date(Math.max(from.getTime(), now.getTime())), to, protectedTime, timeZone, days);
}
